def get_error_message(error_code: int) -> str:
    """根据错误码获取错误信息"""
    return ERROR_CODES.get(error_code, f"未知错误码: {error_code}")


def format_error(error_code: int) -> str:
    """格式化错误信息为 err_code:err_message 格式"""
    return f"{error_code}:{get_error_message(error_code)}"
